/**
 * Measures the rule-based services against the seed dataset's ground truth.
 *
 * The generator injects a known set of bad transactions, so the anomaly
 * detector can be scored rather than merely demonstrated. The same harness is
 * how a future learned model will be compared against these rules - if it does
 * not beat these numbers on the same split, it does not ship.
 */
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { buildPriceIndex, RuleBasedValuer, type PricePoint } from '@ewaste/shared';
import { parseCsv } from '../src/csv.ts';

const dataDir = join(dirname(fileURLToPath(import.meta.url)), '..', 'data');
const read = (f: string) => readFileSync(join(dataDir, f), 'utf8');

const meta = JSON.parse(read('meta.json')) as { windowEnd: string };
const transactions = parseCsv(read('transactions.csv'));
const truth = parseCsv(read('anomaly_ground_truth.csv'));
const truthIds = new Set(truth.map((t) => t['transactionId']));

/* Anomaly detection: precision and recall against the injected anomalies. */
const flagged = new Set(transactions.filter((t) => t['anomalyFlags'] !== '').map((t) => t['transactionId']));

let tp = 0;
let fp = 0;
let fn = 0;
for (const t of transactions) {
  const id = t['transactionId']!;
  const isBad = truthIds.has(id);
  const wasFlagged = flagged.has(id);
  if (isBad && wasFlagged) tp++;
  else if (!isBad && wasFlagged) fp++;
  else if (isBad && !wasFlagged) fn++;
}
const precision = tp / (tp + fp || 1);
const recall = tp / (tp + fn || 1);
const f1 = (2 * precision * recall) / (precision + recall || 1);

console.log('Anomaly detection vs injected ground truth');
console.log(`  transactions        ${transactions.length}`);
console.log(`  injected anomalies  ${truthIds.size}`);
console.log(`  flagged             ${flagged.size}`);
console.log(`  true positives      ${tp}`);
console.log(`  false positives     ${fp}`);
console.log(`  false negatives     ${fn}`);
console.log(`  precision           ${precision.toFixed(3)}`);
console.log(`  recall              ${recall.toFixed(3)}`);
console.log(`  f1                  ${f1.toFixed(3)}`);

/* Recall broken down by the kind of problem injected. */
const byKind = new Map<string, { total: number; caught: number }>();
for (const row of truth) {
  const kind = row['kind']!;
  const entry = byKind.get(kind) ?? { total: 0, caught: 0 };
  entry.total++;
  if (flagged.has(row['transactionId']!)) entry.caught++;
  byKind.set(kind, entry);
}
console.log('\n  recall by injected kind');
for (const [kind, { total, caught }] of byKind) {
  console.log(`    ${kind.padEnd(18)} ${caught}/${total}  ${(caught / total).toFixed(2)}`);
}

/* Valuation: how close the estimate lands to the settled price. */
const prices = parseCsv(read('prices.csv')).map(
  (r) =>
    ({
      ...r,
      buyingPriceInr: Number(r['buyingPriceInr']),
      marketLowInr: Number(r['marketLowInr']),
      marketHighInr: Number(r['marketHighInr']),
      confidence: Number(r['confidence']),
    }) as unknown as PricePoint,
);
const priceIndex = buildPriceIndex(prices, { now: new Date(meta.windowEnd), windowDays: 90 });
void new RuleBasedValuer(priceIndex);

const clean = transactions.filter((t) => !truthIds.has(t['transactionId']!));
const errorsPct = clean
  .map((t) => {
    const estimated = Number(t['estimatedValueInr']);
    const final = Number(t['finalPriceInr']);
    return estimated > 0 ? Math.abs(final - estimated) / estimated : 0;
  })
  .sort((a, b) => a - b);
const mape = errorsPct.reduce((s, e) => s + e, 0) / (errorsPct.length || 1);
const median = errorsPct[Math.floor(errorsPct.length / 2)] ?? 0;
const within20 = errorsPct.filter((e) => e <= 0.2).length / (errorsPct.length || 1);

console.log('\nValuation estimate vs settled price (clean transactions only)');
console.log(`  transactions        ${clean.length}`);
console.log(`  median error        ${(median * 100).toFixed(1)}%`);
console.log(`  mean absolute error ${(mape * 100).toFixed(1)}%`);
console.log(`  within 20%          ${(within20 * 100).toFixed(1)}%`);
console.log('\nNote: this scores the rules against synthetic data generated by a');
console.log('related process, so it is a regression baseline, not field accuracy.');
